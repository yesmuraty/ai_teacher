async def main():
    bot = Bot(token=BOT_TOKEN)
    print(f"DB: {DB_PATH} | Teacher TG: {TEACHER_TG_ID}\n")

    async with aiosqlite.connect(DB_PATH) as db:
        async with db.execute("SELECT id FROM teachers WHERE tg_id = ?", (TEACHER_TG_ID,)) as cur:
            row = await cur.fetchone()

        if row:
            teacher_id = row[0]
            print(f"✅ Мұғалім табылды, ID: {teacher_id}")
        else:
            try:
                chat = await bot.get_chat(TEACHER_TG_ID)
                name = f"{chat.first_name or ''} {chat.last_name or ''}".strip() or "Мұғалім"
            except Exception:
                name = "Мұғалім"
            await db.execute("INSERT INTO teachers (tg_id, full_name) VALUES (?, ?)", (TEACHER_TG_ID, name))
            await db.commit()
            async with db.execute("SELECT id FROM teachers WHERE tg_id = ?", (TEACHER_TG_ID,)) as cur:
                teacher_id = (await cur.fetchone())[0]
            print(f"✅ Мұғалім тіркелді: {name}, ID: {teacher_id}")

        await db.execute("DELETE FROM tasks WHERE teacher_id = ?", (teacher_id,))
        await db.commit()
        print("🗑 Ескі тапсырмалар жойылды\n")

        for i, task in enumerate(TASKS, 1):
            await db.execute(
                "INSERT INTO tasks (teacher_id, skill, title, description, file_id, file_type) VALUES (?, ?, ?, ?, ?, ?)",
                (teacher_id, task["skill"], task["title"], task["description"], None, "text")
            )
            print(f"[{i}/{len(TASKS)}] ✅ {task['title']}")
        await db.commit()

    print(f"\n🎉 {len(TASKS)} тапсырма қосылды!")
    try:
        await bot.send_message(TEACHER_TG_ID, f"✅ {len(TASKS)} тапсырма базаға сәтті қосылды!")
    except Exception as e:
        print(f"Хабарлама жіберілмеді: {e}")
    await bot.session.close()


if __name__ == "__main__":
    asyncio.run(main())
