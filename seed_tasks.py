async def get_or_create_teacher(db, bot) -> int:
    """Мұғалімді базадан алады немесе жасайды"""
    async with db.execute("SELECT id FROM teachers WHERE tg_id = ?", (TEACHER_TG_ID,)) as cur:
        row = await cur.fetchone()
        if row:
            return row[0]

    # Мұғалімнің атын ботқа сұраймыз
    try:
        chat = await bot.get_chat(TEACHER_TG_ID)
        name = f"{chat.first_name or ''} {chat.last_name or ''}".strip() or "Мұғалім"
    except Exception:
        name = "Мұғалім"

    await db.execute(
        "INSERT INTO teachers (tg_id, full_name) VALUES (?, ?)",
        (TEACHER_TG_ID, name)
    )
    await db.commit()
    async with db.execute("SELECT id FROM teachers WHERE tg_id = ?", (TEACHER_TG_ID,)) as cur:
        return (await cur.fetchone())[0]


async def upload_file(bot: Bot, file_path: str, file_type: str) -> str | None:
    """Файлды Telegram-ға жүктеп, file_id қайтарады"""
    try:
        f = FSInputFile(file_path)
        if file_type == "photo":
            msg = await bot.send_photo(TEACHER_TG_ID, f)
            await bot.delete_message(TEACHER_TG_ID, msg.message_id)
            return msg.photo[-1].file_id
        elif file_type == "audio":
            msg = await bot.send_audio(TEACHER_TG_ID, f)
            await bot.delete_message(TEACHER_TG_ID, msg.message_id)
            return msg.audio.file_id
    except Exception as e:
        print(f"  ⚠️ Файл жүктеу қатесі: {e}")
        return None


async def seed():
    bot = Bot(token=BOT_TOKEN)

    print("🚀 Тапсырмаларды базаға қосу басталды...\n")

    async with aiosqlite.connect(DB_PATH) as db:
        teacher_id = await get_or_create_teacher(db, bot)
        print(f"✅ Мұғалім ID: {teacher_id}\n")

        # Бар тапсырмаларды тексер
        async with db.execute("SELECT COUNT(*) FROM tasks WHERE teacher_id = ?", (teacher_id,)) as cur:
            count = (await cur.fetchone())[0]
            if count > 0:
                print(f"⚠️ Базада {count} тапсырма бар. Қайта қосу? (y/n): ", end="")
                if input().strip().lower() != "y":
                    print("Тоқтатылды.")
                    await bot.session.close()
                    return

        for i, task in enumerate(TASKS, 1):
            print(f"[{i}/{len(TASKS)}] {task['title']}")

            file_id = None
            file_type = task["media_type"]

            if task["media_key"] and task["media_key"] in FILES:
                file_path = FILES[task["media_key"]]
                print(f"  📤 Файл жүктелуде: {file_path}")
                file_id = await upload_file(bot, file_path, file_type)
                if file_id:
                    print(f"  ✅ file_id алынды")
                else:
                    print(f"  ❌ Файл жүктелмеді, мәтін ретінде сақталады")
                    file_type = "text"

            await db.execute(
                "INSERT INTO tasks (teacher_id, skill, title, description, file_id, file_type) VALUES (?, ?, ?, ?, ?, ?)",
                (teacher_id, task["skill"], task["title"], task["description"], file_id, file_type)
            )
            await db.commit()
            print(f"  💾 Базаға жазылды\n")

    print(f"🎉 Барлық {len(TASKS)} тапсырма сәтті қосылды!")
    await bot.session.close()


if __name__ == "__main__":
    asyncio.run(seed())
